import Foundation

/// Що користувач хотів зробити, коли програма спитала «Зберегти зміни в каталозі?» (прецедент UC-22).
///
/// Поки користувач відповідає (і, можливо, вибирає, куди зберегти), дія чекає в `CatalogViewModel.pendingAction`;
/// після «Зберегти» або «Не зберігати» вона виконується, після «Скасувати» — забувається.
enum PendingFileAction {
    /// «Новий каталог».
    case newCatalog
    /// «Відкрити…» — показати вікно вибору файлу.
    case openFile
    /// «Демо-дані».
    case demoData
}

import Foundation

/// Результат функції 1–6. Усі функції повертають результат однакового вигляду, тому інтерфейс показує
/// їх одним і тим самим способом: 1 група для списку (ф.1–4), 2 групи для ф.5, N груп для ф.6.
struct OperationResult {
    /// Що саме зроблено, наприклад «Технологія «Swift»» або «За спаданням середньої зарплати».
    let title: String
    /// Короткий підсумок праворуч над таблицею, наприклад «Знайдено 3 вакансії».
    let summary: String
    /// Вакансії результату (посилання на об'єкти з каталогу; каталог не змінюється).
    let groups: [VacancyGroup]

    /// Скільки вакансій у всіх групах разом.
    var vacancyCount: Int {
        var count = 0
        for group in groups {
            count += group.vacancies.count
        }
        return count
    }
}

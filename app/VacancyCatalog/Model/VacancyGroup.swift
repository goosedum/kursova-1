import Foundation

/// Група вакансій із заголовком.
///
/// Результат функцій 1–4 — одна група («Знайдено»), функції 5 — дві (найменший і найбільший діапазон),
/// функції 6 — по групі на кожну спеціалізацію.
struct VacancyGroup: Identifiable {
    /// Заголовок групи, наприклад «Backend» або «Найменший діапазон — $300».
    let title: String
    /// Вакансії групи (посилання на об'єкти з каталогу, не копії).
    let vacancies: [Vacancy]

    /// Ідентифікатор для списків SwiftUI — заголовок, бо в межах одного результату він унікальний.
    var id: String {
        return title
    }
}

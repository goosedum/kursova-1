import Foundation

/// Найменший і найбільший діапазон зарплати (макс − мін) у каталозі — результат функції 5.
///
/// Якщо однаковий крайній діапазон мають кілька вакансій, у масив потрапляють **усі** вони.
struct SalaryRangeExtremes {
    /// Найменший діапазон зарплати, $.
    let minRange: Int
    /// Вакансії з найменшим діапазоном.
    let minRangeVacancies: [Vacancy]
    /// Найбільший діапазон зарплати, $.
    let maxRange: Int
    /// Вакансії з найбільшим діапазоном.
    let maxRangeVacancies: [Vacancy]
}

//
//  HelpTopic.swift
//  Розділи вікна «Довідка»: назва, іконка, вступ, кроки, приклад і порада.
//

import Foundation

/// Розділ довідки (Figma: `Organism/HelpWindow`, екран S-19; прецедент UC-17).
///
/// Текст кожного розділу — тут, а `HelpView` показує будь-який розділ однаково: заголовок, вступ,
/// пронумеровані кроки, приклад (для формату файлу) і порада внизу.
enum HelpTopic: String, CaseIterable, Identifiable {
    /// «Початок роботи» — перші кроки.
    case gettingStarted
    /// «Файли» — відкриття, збереження, помилки у файлі.
    case files
    /// «Вакансії» — додавання, редагування, дублювання, видалення.
    case vacancies
    /// «Функції 1–6» — що робить кожна функція.
    case functions
    /// «Гарячі клавіші».
    case shortcuts
    /// «Формат файлу» — правила і приклад рядка.
    case fileFormat

    /// Ідентифікатор для списку SwiftUI.
    var id: String {
        return rawValue
    }

    /// Назва розділу в сайдбарі довідки і заголовок сторінки.
    var title: String {
        switch self {
        case .gettingStarted:
            return "Початок роботи"
        case .files:
            return "Файли"
        case .vacancies:
            return "Вакансії"
        case .functions:
            return "Функції 1–6"
        case .shortcuts:
            return "Гарячі клавіші"
        case .fileFormat:
            return "Формат файлу"
        }
    }

    /// Іконка SF Symbols.
    var systemImage: String {
        switch self {
        case .gettingStarted:
            return "info.circle"
        case .files:
            return "folder"
        case .vacancies:
            return "briefcase"
        case .functions:
            return "chart.bar.doc.horizontal"
        case .shortcuts:
            return "command"
        case .fileFormat:
            return "doc"
        }
    }

    /// Вступ під заголовком.
    var intro: String {
        switch self {
        case .gettingStarted:
            return "«Каталог вакансій» зберігає вакансії для ІТ-спеціалістів у текстовому файлі й допомагає швидко "
                + "знайти, відібрати, впорядкувати та згрупувати їх."
        case .files:
            return "Каталог зберігається у звичайному текстовому файлі (.txt, UTF-8): одна вакансія — один рядок."
        case .vacancies:
            return "Кожна вакансія має 8 полів: компанія, посада, спеціалізація, рівень досвіду, мінімальна і "
                + "максимальна зарплата ($ на місяць), формат роботи і технології."
        case .functions:
            return "Функції вибираються в сайдбарі, у меню «Аналіз» або клавішами ⌘1…⌘6. Каталог під час аналізу "
                + "не змінюється — показується результат."
        case .shortcuts:
            return "Усі дії доступні з меню; найчастіші — ще й з клавіатури."
        case .fileFormat:
            return "8 полів через «;», технології через «,». Рядки, що починаються з «#», — коментарі, порожні "
                + "рядки пропускаються."
        }
    }

    /// Пронумеровані кроки або пункти розділу.
    var steps: [String] {
        switch self {
        case .gettingStarted:
            return [
                "Відкрийте файл каталогу: Файл → Відкрити… (⌘O) або кнопка на панелі інструментів. "
                    + "Щоб спробувати програму, натисніть «Демо-дані» в порожньому вікні.",
                "Виберіть вакансію в таблиці — усі її дані з'являться на панелі деталей (кнопка праворуч на панелі).",
                "Щоб додати вакансію, натисніть «+» (⌘N); щоб змінити — двічі клацніть рядок або натисніть ⌘E.",
                "Функції 1–6 — у сайдбарі, у меню «Аналіз» або клавішами ⌘1…⌘6. Задайте параметри й натисніть "
                    + "«Виконати» (⌘⏎).",
                "Збережіть каталог: Файл → Зберегти (⌘S). Поки зміни не збережено, рядок стану показує "
                    + "«Є незбережені зміни»."
            ]
        case .files:
            return [
                "Відкрити… (⌘O) — вибрати файл .txt. Якщо в рядку файлу помилка, програма покаже її номер і "
                    + "причину, а відкритий каталог не зміниться.",
                "Зберегти (⌘S) — записати каталог у поточний файл; Зберегти як… (⇧⌘S) — у новий.",
                "Новий каталог (⇧⌘N) — почати з порожнього каталогу.",
                "Перед відкриттям іншого файлу чи новим каталогом програма спитає, чи зберегти зміни."
            ]
        case .vacancies:
            return [
                "Додати (⌘N): заповніть форму; помилки видно під полями. «Зберегти» завжди активна — якщо дані "
                    + "неправильні, з'явиться повідомлення, що виправити.",
                "Редагувати (⌘E або подвійний клік): форма змінює копію вакансії, тому «Скасувати» залишає "
                    + "оригінал без змін.",
                "Дублювати (⌘D): копія з'являється одразу під оригіналом.",
                "Видалити (⌘⌫): можна вибрати кілька рядків (⌘-клік, ⇧-клік) і видалити їх разом.",
                "Правила: текстові поля не порожні; зарплата від 0 до 100 000 $, мінімальна не більша за "
                    + "максимальну; від 1 до 15 технологій."
            ]
        case .functions:
            return [
                "Пошук за посадою і компанією — обидва поля разом, без урахування регістру; порожнє поле — "
                    + "будь-яке значення.",
                "Пошук за технологією — точний збіг назви: «Swift» не знаходить «SwiftUI».",
                "Рівень досвіду і формат роботи — вакансії, у яких збігаються обидва значення.",
                "Сортування за середньою зарплатою — власне сортування злиттям; рівні значення зберігають порядок.",
                "Найменший і найбільший діапазон зарплати — усі вакансії з крайніми значеннями, зокрема однакові.",
                "Групування за спеціалізацією — групи за абеткою, у групі — від більшої максимальної зарплати."
            ]
        case .shortcuts:
            return [
                "⇧⌘N — новий каталог · ⌘O — відкрити · ⌘S — зберегти · ⇧⌘S — зберегти як",
                "⌘N — додати вакансію · ⌘E — редагувати · ⌘D — дублювати · ⌘⌫ — видалити",
                "⌘0 — усі вакансії · ⌘1…⌘6 — функції 1–6 · ⌘⏎ — виконати функцію",
                "⌘? — ця довідка · Esc — закрити форму без змін"
            ]
        case .fileFormat:
            return [
                "Порядок полів: компанія; посада; спеціалізація; рівень; мінімальна зарплата; максимальна "
                    + "зарплата; формат; технології.",
                "Рівень: Intern, Junior, Middle, Senior або Lead. Формат: Office, Remote або Hybrid.",
                "Зарплата — ціле число доларів; мінімальна не більша за максимальну.",
                "Під час збереження програма сама пише рядок-коментар із назвами полів."
            ]
        }
    }

    /// Приклад (рядки файлу) або порожній рядок, якщо прикладу немає.
    var example: String {
        if self == .fileFormat {
            return "# компанія;посада;спеціалізація;рівень;мін;макс;формат;технології\n"
                + "ByteForge;Junior iOS Developer;Mobile;Junior;800;1200;Office;Swift,UIKit,Git"
        }
        return ""
    }

    /// Порада внизу сторінки або порожній рядок.
    var tip: String {
        switch self {
        case .gettingStarted:
            return "Наведіть курсор на будь-яку кнопку чи поле — через мить з'явиться підказка, що воно робить."
        case .files:
            return "Приклади файлів із помилками для перевірки — у папці samples репозиторію."
        default:
            return ""
        }
    }
}

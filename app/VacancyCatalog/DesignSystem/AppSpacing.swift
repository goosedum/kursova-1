import SwiftUI

/// Відступи між елементами і всередині них (колекція `Spacing` у Figma, сторінка 01 Foundations).
///
/// У коді інтерфейсу не пишемо «магічних» чисел — лише ці назви, тож Figma і програма завжди збігаються.
/// Це `enum` без випадків: лише набір констант, створити його об'єкт не можна.
enum AppSpacing {
    /// 2 pt — між рядками підпису зарплати, поля панелі деталей.
    static let xxs: CGFloat = 2
    /// 4 pt — усередині бейджів по вертикалі, між чипами технологій.
    static let xs: CGFloat = 4
    /// 8 pt — усередині чипа по горизонталі, між елементами рядка.
    static let s: CGFloat = 8
    /// 12 pt — усередині бейджа по горизонталі, між підписом і полем форми.
    static let m: CGFloat = 12
    /// 16 pt — поля вмісту вікна.
    static let l: CGFloat = 16
    /// 20 pt.
    static let xl: CGFloat = 20
    /// 24 pt — поля листа (форми).
    static let xxl: CGFloat = 24
    /// 32 pt — відступи порожнього стану.
    static let xxxl: CGFloat = 32
}
